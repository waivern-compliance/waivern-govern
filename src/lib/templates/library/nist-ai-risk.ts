/**
 * AI risk identification, following NIST AI RMF 1.0.
 *
 * The same job as the DSIT identification template, organised the way NIST
 * is: MAP to establish context, categorise the system, weigh benefits and
 * costs, and map third parties and impacts; then one section per
 * characteristic of trustworthy AI, as MEASURE 2 evaluates them; then the
 * go or no-go determination MANAGE 1.1 asks for. Each question cites the
 * subcategory it serves, so an assessment doubles as evidence towards a NIST
 * profile.
 *
 * Questions the AI register, the approval workflow and ATRS records read —
 * consequence, human oversight, monitoring, bias, contestability, model
 * choice, personal data, public facing, spend, the review interval — keep the
 * DSIT template's keys and options exactly, so this template feeds them
 * without a second mapping and an organisation can move between frameworks
 * without the register losing what it knows. Scored questions shared with the
 * DSIT template keep their weights, and the bands sit at the same points, so a
 * system lands in the same tier whichever template assessed it.
 *
 * Questions on UK law — data protection, equality, ATRS — stay. They are
 * obligations whichever framework an organisation follows, and NIST's own
 * GOVERN 1.1 asks for applicable law to be met.
 */
